/*
 * Simulated arXiv service. The curated entries and the synthesized ones are
 * synthetic (see content/papers.ts); nothing here touches the network.
 */
import { AUTHOR_POOL, DOMAIN_HINTS, PAPERS, SYNTH_TEMPLATES } from '../content/papers';
import type { DomainId, FeedPaper, Paper } from '../content/types';
import { hashStr } from './format';

export type FeedSort = 'relevance' | 'date';

/** Relevance of a paper to a keyword (0 = no match). */
export function matchScore(paper: Paper, kw: string): number {
  const norm = (s: string) => s.toLowerCase().replace(/[\s\-–_]+/g, '');
  const k = norm(kw);
  if (!k) return 0;
  let score = 0;
  if (paper.keywords.some(x => norm(x).includes(k) || k.includes(norm(x)))) score += 3;
  if (norm(paper.title).includes(k)) score += 2;
  if (norm(paper.abstract).includes(k)) score += 1;
  return score;
}

export function guessDomain(kw: string): DomainId {
  for (const [id, re] of DOMAIN_HINTS) if (re.test(kw)) return id;
  return (['ant', 'algnt', 'cnt', 'crypto', 'pqc'] as const)[hashStr(kw) % 5];
}

/** Deterministic synthetic papers for a keyword with no curated match. */
export function synthPapers(kw: string): Paper[] {
  const domain = guessDomain(kw);
  const h = hashStr(kw.toLowerCase());
  return SYNTH_TEMPLATES[domain].map((tpl, i) => {
    const hh = hashStr(kw + ':' + i);
    const fill = (s: string) => s.split('{KW}').join(kw);
    const nAuthors = 2 + (hh % 3);
    const authors = Array.from({ length: nAuthors }, (_, j) => AUTHOR_POOL[(hh + j * 7) % AUTHOR_POOL.length]);
    const day = 1 + ((h + i * 5) % 14);
    return {
      id: '2610.' + String(10000 + (hh % 89999)).padStart(5, '0'),
      date: '2026-10-' + String(day).padStart(2, '0'),
      domain,
      cats: domain === 'pqc' || domain === 'crypto' ? ['cs.CR', 'math.NT'] : ['math.NT'],
      title: fill(tpl.title),
      authors: [...new Set(authors)],
      keywords: [kw],
      abstract: fill(tpl.abstract),
      result: fill(tpl.result),
      context: 'Generated by the feed simulator for the tracked keyword "' + kw + '".',
      generated: true
    };
  });
}

/** Curated papers plus synthesized ones for keywords that match none of them. */
export function paperPool(keywords: string[]): Paper[] {
  const pool: Paper[] = [...PAPERS];
  keywords.forEach(k => {
    if (!PAPERS.some(p => matchScore(p, k) > 0)) pool.push(...synthPapers(k));
  });
  return pool;
}

export function computeFeed(keywords: string[], domain: DomainId | 'all', sort: FeedSort): FeedPaper[] {
  const pool: FeedPaper[] = paperPool(keywords).map(p => ({
    ...p,
    matched: keywords.filter(k => matchScore(p, k) > 0),
    score: keywords.reduce((s, k) => s + matchScore(p, k), 0)
  }));
  let list = keywords.length ? pool.filter(p => p.matched.length) : pool;
  if (domain !== 'all') list = list.filter(p => p.domain === domain);
  list.sort(sort === 'date' ? (a, b) => b.date.localeCompare(a.date) : (a, b) => b.score - a.score || b.date.localeCompare(a.date));
  return list;
}

/** Look a paper up by id, including synthesized entries for the given keywords. */
export function findPaper(id: string, keywords: string[]): Paper | undefined {
  return paperPool(keywords).find(p => p.id === id);
}

export function bibtex(p: Paper): string {
  const key =
    p.authors[0].split(' ').pop()!.normalize('NFD').replace(/[^\w]/g, '').toLowerCase() +
    p.date.slice(0, 4) +
    p.title.split(/\s+/)[0].replace(/[^\w]/g, '').toLowerCase();
  return (
    '@misc{' + key + ',\n  title         = {' + p.title + '},\n  author        = {' + p.authors.join(' and ') +
    '},\n  year          = {' + p.date.slice(0, 4) + '},\n  eprint        = {' + p.id +
    '},\n  archivePrefix = {arXiv},\n  primaryClass  = {' + p.cats[0] +
    '},\n  note          = {Synthetic entry from the Arithmos simulated feed}\n}'
  );
}

export const KEYWORD_LIMIT = 12;

/** Returns an error message, or null when the keyword can be added. */
export function validateKeyword(kw: string, existing: string[]): string | null {
  if (!kw) return 'Type a keyword first.';
  if (kw.length < 2 || kw.length > 40) return 'Keywords must be 2–40 characters.';
  if (!/^[\p{L}\p{N}][\p{L}\p{N}\s\-–'’.+()/]*$/u.test(kw)) return 'Use letters, digits, spaces and - . + ( ) / only.';
  if (existing.some(k => k.toLowerCase() === kw.toLowerCase())) return '"' + kw + '" is already tracked.';
  if (existing.length >= KEYWORD_LIMIT) return 'You can track up to ' + KEYWORD_LIMIT + ' keywords; remove one first.';
  return null;
}
